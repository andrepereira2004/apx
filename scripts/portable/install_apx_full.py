#!/usr/bin/env python3
"""Experimental fresh-Arch graphical APX installation; no physical disk writes."""
from __future__ import annotations
import argparse
import ast
import getpass
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

REPO = Path(__file__).resolve().parents[2]
STATE = Path("/var/lib/apx")
LIBRARY = Path("/usr/lib/apx")
GRAPHICAL_PACKAGES = (
    "hyprland", "quickshell", "qt6-declarative", "qt6-svg", "qt6-5compat", "qt6-wayland",
    "qt6-imageformats", "qt6-multimedia", "qt6-shadertools", "mesa", "vulkan-swrast",
    "pipewire", "pipewire-pulse", "wireplumber", "gnome-keyring", "python-gobject", "python-dbus",
    "hyprlock", "hypridle", "hyprpolkitagent", "kitty", "rofi", "mako", "wl-clipboard",
    "xdg-desktop-portal", "xdg-desktop-portal-gtk", "xdg-desktop-portal-hyprland", "xdg-user-dirs",
    "polkit", "libsecret", "jq", "curl", "fastfetch", "grim", "flatpak", "noto-fonts", "noto-fonts-emoji",
    "ttf-liberation", "papirus-icon-theme", "adwaita-icon-theme", "playerctl", "procps-ng",
)
ADAPTERS = (
    "apx-portable-full-runtime.py", "apx-portable-services.py", "apx-portable-graphical.py",
    "apx-portable-session.sh", "apx-portable-compositor.sh", "apx-portable-power.py",
)
SERVICES = ("host-services-v1", "host-services-v2", "host-services-v3", "audio-state-v1",
            "environment-switch-v1", "system-power-v1", "environment-hardware-v1", "coordinated-update-v1")


def module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


def manifests():
    result = {}
    for node in ast.parse((REPO / "scripts/virtual-lab/apx-lab-runtime.py").read_text()).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in {
                    "ENVIRONMENT_SHELL_ASSETS", "GRAPHICAL_CONFIG_ASSETS", "DESKTOP_CONFIG_ASSETS"}:
                    result[target.id] = ast.literal_eval(node.value)
    return result


def source_files():
    # Explicit source trees, never /home, the live Hub or generated bytecode.
    files = {"LICENSE"}
    for folder in ("src", "scripts/physical-pilot"):
        files.update(str(path.relative_to(REPO)) for path in (REPO / folder).glob("*.py"))
    files.update("scripts/portable/" + name for name in ADAPTERS)
    files.update({"scripts/portable/install_apx_full.py", "scripts/portable/install-apx-full.sh",
                  "scripts/portable/install_apx_disk.py", "scripts/portable/finish-apx-first-boot.sh",
                  "scripts/portable/install_apx_arch.py", "scripts/portable/install-apx-arch.sh",
                  "scripts/portable/apx-portable-runtime.py", "scripts/virtual-lab/apx-lab-runtime.py",
                  "scripts/virtual-lab/apx-lab-client.py", "scripts/virtual-lab/apx-lab-executor.py"})
    for relative in manifests()["ENVIRONMENT_SHELL_ASSETS"]:
        files.add("config/environment-shell-v1/" + relative)
    for relative in manifests()["GRAPHICAL_CONFIG_ASSETS"]:
        files.add("config/hyprland-base/" + ("hyprland.conf" if relative == "hyprland/hyprland.conf" else relative))
    for relative in manifests()["DESKTOP_CONFIG_ASSETS"]:
        files.add("config/waybar-ascii-v1/" + relative)
    files.update(str(path.relative_to(REPO)) for path in (REPO / "config/environment-flatpak-v1").iterdir() if path.is_file())
    return sorted(files)


def verify_sources():
    hashes = {}
    for relative in source_files():
        path = REPO / relative
        if path.is_symlink() or not path.is_file():
            raise ValueError("missing/unsafe source: " + relative)
        hashes[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    for group, prefix in (("ENVIRONMENT_SHELL_ASSETS", "config/environment-shell-v1/"),
                          ("DESKTOP_CONFIG_ASSETS", "config/waybar-ascii-v1/"),
                          ("GRAPHICAL_CONFIG_ASSETS", "config/hyprland-base/")):
        for name, expected in manifests()[group].items():
            relative = prefix + ("hyprland.conf" if group == "GRAPHICAL_CONFIG_ASSETS" and name == "hyprland/hyprland.conf" else name)
            if hashes[relative] != expected:
                raise ValueError("source does not match its admitted digest: " + relative)
    return hashes


def full_install(base, record, password, hardware):
    base.install(record)
    progress = {"schema": 1, "profile": "portable-graphical-v1", "phase": "base-installed",
                "source_sha256": verify_sources(), "status": "experimental-not-yet-accepted"}
    def checkpoint(phase):
        progress["phase"] = phase
        base.write(STATE / "portable-graphical-install.json", json.dumps(progress, indent=2) + "\n", 0o600)
    checkpoint("base-installed")
    base.run("systemctl", "disable", "--now", "apx-portable-hub.service")
    # The initial headless Hub has no owner data or enrolled identity. Replace
    # only this installer's newly created stopped instance, using its lifecycle.
    plan = json.loads(base.run("apx", "environment", "destroy-plan", "hub", capture=True))
    base.run("apx", "environment", "destroy", "--plan", plan["digest"], "--approve", "DESTROY hub")
    for relative in source_files():
        source = REPO / relative
        if relative.startswith(("src/", "scripts/physical-pilot/")):
            shutil.copyfile(source, LIBRARY / source.name)
            (LIBRARY / source.name).chmod(0o755 if relative.startswith("scripts/") else 0o644)
    for filename in ADAPTERS:
        shutil.copyfile(REPO / "scripts/portable" / filename, LIBRARY / filename)
        (LIBRARY / filename).chmod(0o755)
    # All helper imports in each private root resolve to these source modules.
    seeds = Path("/usr/share/apx/config-seeds")
    for group, target, prefix in (
            ("ENVIRONMENT_SHELL_ASSETS", "environment-shell-v1", "config/environment-shell-v1"),
            ("DESKTOP_CONFIG_ASSETS", "desktop-essential-v1", "config/waybar-ascii-v1")):
        for relative in manifests()[group]:
            destination = seeds / target / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(REPO / prefix / relative, destination)
    directory = STATE / "releases/hyprland-base-v2"
    directory.mkdir()
    root = directory / "root"
    base.run("btrfs", "subvolume", "snapshot", str(STATE / "releases/minimal-headless-v1/root"), str(root))
    legacy = root / "usr/share/apx/config-seeds/hyprland-minimal-v2"
    for relative in manifests()["GRAPHICAL_CONFIG_ASSETS"]:
        source = REPO / "config/hyprland-base" / ("hyprland.conf" if relative == "hyprland/hyprland.conf" else relative)
        destination = legacy / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    graphics_packages = list(GRAPHICAL_PACKAGES)
    # Share only the declared public hardware package selection, never live roots.
    disk_record = Path('/etc/apx-empty-disk-install.json')
    if disk_record.is_file() and not disk_record.is_symlink():
        info = disk_record.stat()
        if info.st_uid or info.st_mode & 0o022:
            raise ValueError('untrusted disk installation record')
        selected = json.loads(disk_record.read_text())['hardware']['graphics_packages']
        allowed = {'mesa', 'vulkan-swrast', 'vulkan-intel', 'vulkan-radeon', 'nvidia-open', 'nvidia-utils', 'egl-wayland'}
        if not isinstance(selected, list) or any(p not in allowed for p in selected):
            raise ValueError('invalid hardware package selection')
        graphics_packages += [p for p in selected if p != 'nvidia-open']
    if hardware['graphics']['driver'] == 'nvidia':
        graphics_packages += ['nvidia-utils', 'egl-wayland', 'egl-gbm', 'egl-x11', 'egl-wayland2']
    base.run("pacman", "--root", str(root), "--dbpath", str(root / "var/lib/pacman"),
             "--config", str(root / "etc/pacman.conf"), "--cachedir", "/var/cache/pacman/pkg",
             "--disable-sandbox", "-Syu", "--needed", "--noconfirm", *graphics_packages)
    if hardware['graphics']['driver'] == 'nvidia':
        version = Path('/sys/module/nvidia/version').read_text().strip()
        library = root / 'usr/lib/libEGL_nvidia.so.0'
        if not library.is_symlink() or os.readlink(library) != 'libEGL_nvidia.so.' + version:
            raise ValueError('NVIDIA userspace does not match the running Host module; inspect the install journal and reboot before graphical admission')
    locale_gen = root / "etc/locale.gen"
    locale_text = locale_gen.read_text()
    for locale in ("en_US.UTF-8 UTF-8", "pt_PT.UTF-8 UTF-8"):
        locale_text = locale_text.replace("#" + locale, locale)
    locale_gen.write_text(locale_text)
    base.run("systemd-nspawn", "--quiet", "--directory=" + str(root), "--register=no", "--private-network",
             "/usr/bin/locale-gen")
    base.write(root / "etc/sudoers.d/10-apx-local-admin", "apx ALL=(root) ALL\n", 0o440)
    inside_library = root / "usr/lib/apx"
    inside_library.mkdir(parents=True, exist_ok=True)
    for source in LIBRARY.glob("*.py"):
        shutil.copy2(source, inside_library / source.name)
    shutil.copy2(LIBRARY / "apx-portable-session.sh", inside_library / "apx-portable-session.sh")
    shutil.copy2(LIBRARY / "apx-portable-compositor.sh", inside_library / "apx-portable-compositor.sh")
    shutil.copy2(LIBRARY / "apx-lab-client.py", root / "usr/bin/apx")
    (root / "usr/bin/apx").chmod(0o755)
    base.write(directory / "manifest.json", json.dumps({"schema": 1, "role": "graphical-base",
               "source": "fresh-signed-Arch-packages-and-repository-seeds"}) + "\n", 0o400)
    base.run("btrfs", "property", "set", "-ts", str(root), "ro", "true")
    hub_release = STATE / "releases/portable-hub-graphical-v1"
    hub_release.mkdir()
    base.run("btrfs", "subvolume", "snapshot", "-r", str(root), str(hub_release / "root"))
    base.write(hub_release / "manifest.json", json.dumps({"schema": 1, "role": "hub",
               "source": "independent-immutable-common-release-not-live-Hub"}) + "\n", 0o400)
    entry = Path("/usr/bin/apx")
    entry.unlink()
    entry.symlink_to(LIBRARY / "apx-portable-full-runtime.py")
    # The authenticated executor imports this exact entry point by its legacy name.
    shutil.copy2(LIBRARY / "apx-portable-full-runtime.py", LIBRARY / "apx-lab-runtime.py")
    plan = json.loads(base.run("apx", "environment", "create-plan", "hub", "--role", "hub", capture=True))
    base.run("apx", "environment", "create", "--plan", plan["digest"], "--approve", "CREATE hub AS hub")
    hub_root = STATE / "environments/hub/root"
    base.run("systemd-nspawn", "--quiet", "--console=pipe", "--directory=" + str(hub_root), "--register=no", "--private-network",
             "/usr/bin/chpasswd", input="apx:" + password + "\n")
    password = None
    bridge = STATE / "environments/hub/home/.apx-host-bridge"
    bridge.mkdir(mode=0o700)
    (STATE / "native-environments").mkdir(mode=0o700, exist_ok=True)
    checkpoint("graphical-release-and-new-identity-created")
    for service in SERVICES:
        base.write(Path("/etc/systemd/system/apx-portable-" + service + ".service"), f'''[Unit]
Description=APX generic authenticated {service}
After=apx-lab-executor.service
RequiresMountsFor=/var/lib/apx

[Service]
ExecStart=/usr/bin/python /usr/lib/apx/apx-portable-services.py {service}
Restart=on-failure
RestartSec=2
UMask=0077

[Install]
WantedBy=multi-user.target
''')
    dependencies = " ".join("apx-portable-" + s + ".service" for s in SERVICES)
    base.write(Path("/etc/systemd/system/apx-portable-graphical.service"), f'''[Unit]
Description=APX generic graphical Hub and workload supervisor
Requires={dependencies} apx-lab-executor.service
After={dependencies} apx-lab-executor.service
Conflicts=getty@tty2.service
RequiresMountsFor=/var/lib/apx

[Service]
ExecStart=/usr/bin/python /usr/lib/apx/apx-portable-graphical.py
KillMode=mixed
TimeoutStopSec=45
UMask=0077

[Install]
WantedBy=multi-user.target
''')
    base.run("systemctl", "daemon-reload")
    base.run("systemctl", "restart", "apx-lab-executor.service")
    # VT2 belongs to the APX seat. logind's automatic getty would otherwise
    # conflict with the graphical supervisor shortly after chvt activates it.
    base.run("systemctl", "mask", "getty@tty2.service", "autovt@tty2.service")
    base.run("systemctl", "enable", "--now", *("apx-portable-" + s + ".service" for s in SERVICES))
    base.run("systemctl", "enable", "apx-portable-graphical.service")
    checkpoint("installed-awaiting-graphical-acceptance")
    print("APX graphical candidate installed. Start with: systemctl start apx-portable-graphical.service", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--apply", action="store_true")
    parser.add_argument("--password-stdin", action="store_true", help="read a new APX password from a private pipe")
    args = parser.parse_args()
    base = module(Path(__file__).with_name("install_apx_arch.py"), "apx_portable_base_installer")
    base.PACKAGES += ["seatd", "bluez", "bluez-utils", "iwd", "kbd"]
    hashes = verify_sources()
    record = base.preflight()
    base.run("busctl", "--system", "--no-pager", "status", capture=True)
    hardware = module(REPO / "src/apx_portable_hardware.py", "apx_portable_hardware_probe").discover()
    if not args.apply:
        print(json.dumps({"base": record, "sources": len(hashes), "hardware": hardware,
                          "status": "experimental graphical candidate; acceptance not yet established"}, indent=2))
        return 0
    password = sys.stdin.readline().rstrip("\n") if args.password_stdin else getpass.getpass("New APX password: ")
    if not 12 <= len(password) <= 255 or "\n" in password or "\r" in password:
        raise ValueError("new APX password must contain 12–255 characters and no line breaks")
    if not args.password_stdin and password != getpass.getpass("Repeat new APX password: "):
        raise ValueError("password confirmation differs")
    full_install(base, record, password, hardware)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"APX full installation refused/failed: {error}", file=sys.stderr)
        raise SystemExit(2)
